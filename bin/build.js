import esbuild from 'esbuild'
import { createHash } from 'node:crypto'
import { copyFile, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { inlineBootFiles, loadBootFiles } from './inline-boot-files.js'

const { dirname } = import.meta
const srcDir = path.join(dirname, '..', 'src')
const watch = process.argv.includes('--watch')
const isDev = watch || process.env.NODE_ENV === 'development'
// `npm run build` writes the committed docs/ (GitHub Pages root); watch/dev
// writes to the untracked .dev/ so it never dirties git or conflicts with a
// production build.
const outDir = isDev
  ? path.join(dirname, '..', '.dev')
  : path.join(dirname, '..', 'docs')

async function hashTree (dir, hash) {
  const entries = (await readdir(dir, { withFileTypes: true }))
    .sort((a, b) => a.name.localeCompare(b.name))
  for (const entry of entries) {
    hash.update(entry.name)
    const fullPath = path.join(dir, entry.name)
    if (entry.isDirectory()) await hashTree(fullPath, hash)
    else hash.update(await readFile(fullPath))
  }
}

// Deploy hash: content hash of the vault sources in src/. Injected into the
// worker so its bytes change on every deploy — the browser detects a new
// worker and the (non-dismissible) update banner appears even when only the
// app's own files changed. The worker's cache name is NOT derived from this
// hash, so deploys don't churn the runtime cache.
const deployHash = createHash('sha256')
await hashTree(srcDir, deployHash)
const launcherDeployHash = deployHash.digest('hex').slice(0, 10)

// Logic hash: content hash of the worker source (excluding the injected
// VERSION line) — the cache name changes exactly when the worker's own
// logic/precache strategy changes.
const swSource = await readFile(path.join(srcDir, 'sw.src.js'), 'utf8')
const versionHash = createHash('sha256')
  .update(swSource.split('\n').filter(line => !/^const VERSION\s*=/.test(line)).join('\n'))
  .digest('hex')
  .slice(0, 10)

const define = {
  IS_DEVELOPMENT: JSON.stringify(isDev),
  IS_PRODUCTION: JSON.stringify(!isDev),
  LAUNCHER_SW_VERSION: JSON.stringify(versionHash),
  LAUNCHER_DEPLOY_HASH: JSON.stringify(launcherDeployHash)
}

// The output dir is fully generated by this build.
await rm(outDir, { recursive: true, force: true })
await mkdir(outDir, { recursive: true })

const appContext = await esbuild.context({
  entryPoints: [path.join(srcDir, 'index.js')],
  outdir: outDir,
  entryNames: 'app',
  chunkNames: 'chunks/[name]-[hash]',
  bundle: true,
  platform: 'browser',
  format: 'esm',
  splitting: true,
  minify: false,
  sourcemap: isDev,
  target: ['es2022'],
  define
})

const swContext = await esbuild.context({
  entryPoints: [path.join(srcDir, 'sw.src.js')],
  outfile: path.join(outDir, 'sw.js'),
  bundle: true,
  platform: 'browser',
  format: 'iife',
  splitting: false,
  minify: false,
  target: ['es2022'],
  define
})

// Copy the authored HTML entry and CSS (referenced via <link>, not bundled),
// inlining the boot failsafe/style and the early SW bootstrap from their
// authored files (bin/inline-boot-files.js) so the deployed index.html stays
// self-contained. Rebuilt once at build start; rebuild (or rerun the build)
// picks up edits.
const indexHtml = inlineBootFiles(
  await readFile(path.join(srcDir, 'index.html'), 'utf8'),
  await loadBootFiles(srcDir)
)
await writeFile(path.join(outDir, 'index.html'), indexHtml)
const stylesDir = path.join(outDir, 'styles')
await mkdir(stylesDir, { recursive: true })
for (const entry of await readdir(path.join(srcDir, 'styles'))) {
  if (entry.endsWith('.css')) {
    await copyFile(path.join(srcDir, 'styles', entry), path.join(stylesDir, entry))
  }
}

// Copy static assets (e.g. favicon.png) to the docs root.
const assetsDir = path.join(srcDir, 'assets')
for (const entry of await readdir(assetsDir)) {
  await copyFile(path.join(assetsDir, entry), path.join(outDir, entry))
}

// Copy runtime-fetched data files (e.g. services/messenger-log/fixtures.json,
// resolved at runtime relative to a chunk) to the output, preserving their
// src-relative path.
async function copyDataFiles (dir) {
  const entries = await readdir(dir, { withFileTypes: true })
  for (const entry of entries) {
    const srcPath = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      await copyDataFiles(srcPath)
    } else if (!/\.(?:js|css|html)$/.test(entry.name)) {
      const dest = path.join(outDir, path.relative(srcDir, srcPath))
      await mkdir(path.dirname(dest), { recursive: true })
      await copyFile(srcPath, dest)
    }
  }
}
await copyDataFiles(path.join(srcDir, 'services'))

if (watch) {
  await Promise.all([appContext.watch(), swContext.watch()])
  const devPort = process.env.PORT || '4000'
  console.log(`watching src/ -> docs/ (sw version ${versionHash}, deploy ${launcherDeployHash})...`)
  if (process.env.EZ_VAULT_DEV !== '1') {
    // Standalone `npm run build:watch`: point at the dev server URLs.
    console.log(`  open http://localhost:${devPort}/ (peer: http://localhost:4001 via "npm run start:peer")`)
    console.log('  run "npm start" in another terminal to serve docs/; the service worker and the update banner are disabled in dev (IS_DEVELOPMENT).')
  }
} else {
  await Promise.all([appContext.rebuild(), swContext.rebuild()])
  await Promise.all([appContext.dispose(), swContext.dispose()])
  console.log(`built docs/app.js, docs/chunks/, docs/sw.js (sw version ${versionHash}, deploy ${launcherDeployHash})`)
}
